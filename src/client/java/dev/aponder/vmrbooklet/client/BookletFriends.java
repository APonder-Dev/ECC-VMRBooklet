package dev.aponder.vmrbooklet.client;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.aponder.vmrbooklet.BookletData;
import dev.aponder.vmrbooklet.BookletEntry;
import dev.aponder.vmrbooklet.VMRBooklet;
import net.fabricmc.loader.api.FabricLoader;

import java.io.IOException;
import java.io.Reader;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Read-only snapshots of other players' progress, imported via a share code
 * from {@code /import <code>} (generated by someone else's {@code /export
 * booklet}). Entirely local, no server/network involved - just a stored copy
 * of whatever was in the code at the moment it was shared.
 */
public final class BookletFriends {

	private record Entry(Map<String, Integer> progress, long importedAtMillis) {
	}

	private static final Path FILE = FabricLoader.getInstance().getConfigDir()
			.resolve("vmrbooklet").resolve("friends.json");

	// Synchronized (not a plain LinkedHashMap) since reads happen on the render
	// thread while /import can, in principle, land from a different thread.
	private static final Map<String, Entry> FRIENDS = Collections.synchronizedMap(new LinkedHashMap<>());

	static {
		load();
	}

	private BookletFriends() {
	}

	public static List<String> names() {
		// Collections.synchronizedMap only makes individual calls atomic; iterating
		// a view (keySet/entrySet) still needs the caller to hold the map's own
		// lock for the whole walk, per that method's own documentation.
		synchronized (FRIENDS) {
			return List.copyOf(FRIENDS.keySet());
		}
	}

	/** Read-only - the map stored per friend is made immutable once, in {@link #put}, not copied on every call here. */
	public static Map<String, Integer> progressOf(String name) {
		Entry entry = FRIENDS.get(name);
		return entry == null ? Map.of() : entry.progress();
	}

	/** @return when this friend was last imported/re-imported, or 0 if unknown. */
	public static long importedAtMillis(String name) {
		Entry entry = FRIENDS.get(name);
		return entry == null ? 0L : entry.importedAtMillis();
	}

	public static void put(String name, Map<String, Integer> progress) {
		// Stored immutable, not the caller's own (possibly still-mutable) map -
		// progressOf() hands this back out directly, so it must never be a map
		// something else could still write into after the fact.
		FRIENDS.put(name, new Entry(Map.copyOf(progress), System.currentTimeMillis()));
		save();
	}

	public static void remove(String name) {
		if (FRIENDS.remove(name) != null) {
			save();
		}
	}

	private static void load() {
		if (!Files.exists(FILE)) {
			return;
		}
		try (Reader reader = Files.newBufferedReader(FILE)) {
			JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
			for (Map.Entry<String, JsonElement> friendEntry : root.entrySet()) {
				JsonObject friendObj = friendEntry.getValue().getAsJsonObject();

				// Back-compat: older friends.json files stored a flat {itemId: amount}
				// object per friend with no timestamp wrapper at all.
				JsonObject progressObj = friendObj.has("progress") ? friendObj.getAsJsonObject("progress") : friendObj;
				long importedAt = friendObj.has("importedAtMillis") ? friendObj.get("importedAtMillis").getAsLong() : 0L;

				// Clamped the same way put() (via BookletShareImport.clampToRequired)
				// already clamps every freshly-imported friend code - a friends.json
				// saved by a pre-clamp-fix build could otherwise reload stuck
				// out-of-range values that only a fresh re-import would correct.
				Map<String, Integer> progress = new LinkedHashMap<>();
				for (Map.Entry<String, JsonElement> item : progressObj.entrySet()) {
					BookletEntry bookletEntry = BookletData.byItemId(item.getKey());
					int value = item.getValue().getAsInt();
					if (bookletEntry != null) {
						value = bookletEntry.clamp(value);
					}
					progress.put(item.getKey(), value);
				}
				FRIENDS.put(friendEntry.getKey(), new Entry(Map.copyOf(progress), importedAt));
			}
		} catch (IOException | RuntimeException e) {
			VMRBooklet.LOGGER.warn("Failed to load booklet friends, starting empty.", e);
		}
	}

	private static void save() {
		try {
			Files.createDirectories(FILE.getParent());
			JsonObject root = new JsonObject();
			synchronized (FRIENDS) {
				for (Map.Entry<String, Entry> friendEntry : FRIENDS.entrySet()) {
					JsonObject progressObj = new JsonObject();
					for (Map.Entry<String, Integer> item : friendEntry.getValue().progress().entrySet()) {
						progressObj.addProperty(item.getKey(), item.getValue());
					}
					JsonObject friendObj = new JsonObject();
					friendObj.add("progress", progressObj);
					friendObj.addProperty("importedAtMillis", friendEntry.getValue().importedAtMillis());
					root.add(friendEntry.getKey(), friendObj);
				}
			}
			try (Writer writer = Files.newBufferedWriter(FILE)) {
				new GsonBuilder().setPrettyPrinting().create().toJson(root, writer);
			}
		} catch (IOException e) {
			VMRBooklet.LOGGER.warn("Failed to save booklet friends.", e);
		}
	}
}
